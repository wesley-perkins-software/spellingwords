/** Looks up a Skill's practice bank, or `undefined` if it doesn't have one yet. */
export function getSkillPracticeBank(skillId: string): SkillPracticeBank | undefined {
  return SKILL_PRACTICE_BANKS[skillId as CuratedSpellingSkillId];
}

/**
 * Maps a bank's items to playable `SpellingWord`s. Plain-string items are
 * resolved against the shared sentence bank, mirroring `spellingLists.ts`'s
 * `toPlayableWords`. `SkillPracticeContextItem`s fill their own `context`
 * template into `exampleSentence` (for speech) and keep the blanked
 * template as `contextSentence` (for on-screen display), flagged
 * `contextRequired` so `/play` knows to present context before the word.
 */
export function toPlayableSkillPracticeWords(bank: SkillPracticeBank): SpellingWord[] {
  return bank.words.map((item) => {
    if (isContextItem(item)) {
      return {
        word: item.word,
        exampleSentence: item.context.replace('___', item.word),
        contextSentence: item.context,
        contextRequired: true,
      };
    }
    return {
      word: item,
      exampleSentence: getSentenceBankEntry(item)?.exampleSentence,
    };
  });
}

/**
 * Selects a bounded, shuffled practice session from a Skill's bank. Default
 * session size of 10 matches the curated-collection default already decided
 * in docs/LEARNING_MODEL.md; a bank smaller than that simply yields the
 * whole (shuffled) bank.
 */
export function selectSkillPracticeSession<T>(
  words: readonly T[],
  sessionSize = 10,
  rng: () => number = Math.random,
): T[] {
  return shuffleWords(words, rng).slice(0, sessionSize);
}
