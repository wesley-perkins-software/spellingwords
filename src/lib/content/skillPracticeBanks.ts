/**
 * A meaning-dependent practice item: `word` cannot be identified from
 * isolated pronunciation alone (a homophone, or another commonly confused
 * spelling), so it carries its own disambiguating sentence. `context` must
 * contain exactly one `___` placeholder standing in for `word`.
 */
export interface SkillPracticeContextItem {
  word: string;
  context: string;
}

/** A bank item is either a plain word (looked up in the shared sentence bank, as before) or a `SkillPracticeContextItem` for meaning-dependent Skills. */
export type SkillPracticeBankItem = string | SkillPracticeContextItem;

/**
 * A Skill practice bank: the canonical, grade-independent pool of practice
 * items for one Skill, distinct from that Skill's (smaller) demonstration
 * set in the Skill's own content frontmatter. See
 * docs/architecture/CONTENT_MODEL.md §3/§4.
 *
 * Most Skills use plain-string items, resolved against the shared sentence
 * bank like any other curated word. Meaning-dependent Skills (Homophones,
 * Commonly Confused Words) use `SkillPracticeContextItem`s instead, so the
 * disambiguating sentence travels with the word rather than being looked up
 * globally by spelling.
 */
export interface SkillPracticeBank {
  skillId: CuratedSpellingSkillId;
  words: SkillPracticeBankItem[];
}

function isContextItem(item: SkillPracticeBankItem): item is SkillPracticeContextItem {
  return typeof item !== 'string';
}

/** The word text of a bank item, regardless of shape — for de-duplication, sorting, etc. */
export function bankItemWord(item: SkillPracticeBankItem): string {
  return isContextItem(item) ? item.word : item;
}

